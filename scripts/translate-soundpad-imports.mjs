function stripBom(value) {
  return value.replace(/^\uFEFF/, '');
}

async function readJson(filePath) {
  return JSON.parse(stripBom(await fs.readFile(filePath, 'utf8')));
}

async function writeJson(filePath, value) {
  await fs.writeFile(filePath, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
}

function baseTitle(entry) {
  const raw = entry.originalFileName || entry.title || '';
  const base = path.basename(raw, path.extname(raw))
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  const prefix = categoryPrefixes.get(entry.sectionId);
  if (!prefix) return base;
  return base.replace(new RegExp(`^${escapeRegExp(prefix).replace(/\s+/g, '\\s+') }\\s*`, 'i'), '').trim() || base;
}

function normalizeKey(value) {
  return value
    .toLowerCase()
    .replace(/[_-]+/g, ' ')
    .replace(/\b0+(\d+)\b/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
}

function translateTitle(entry) {
  const clean = normalizeKey(baseTitle(entry));
  const exact = exactTitles.get(clean);
  if (exact) return exact;

  const numbered = clean.match(/^(.*?)(\d+)$/);
  const stem = numbered ? numbered[1].trim() : clean;
  const number = numbered ? ` ${Number(numbered[2])}` : '';

  for (const [phrase, replacement] of phraseReplacements) {
    if (stem === phrase || stem.startsWith(`${phrase} `) || stem.includes(` ${phrase} `)) {
      const rest = stem === phrase ? '' : stem.replace(phrase, '').trim();
      return smartTitle(`${replacement}${number}${rest ? ` ${fallbackTranslate(rest)}` : ''}`);
    }
  }

  return smartTitle(`${fallbackTranslate(stem)}${number}`);
}

function fallbackTranslate(value) {
  return value
    .split(/\s+/)
    .filter(Boolean)
    .map((token) => tokenMap.get(token) || token)
    .join(' ')
    .replace(/\s+фон$/i, '')
    .trim();
}

function smartTitle(value) {
  const compact = value.replace(/\s+/g, ' ').trim();
  if (!compact) return 'Без названия';
  return compact.charAt(0).toUpperCase() + compact.slice(1);
}

function chooseImage(entry) {
  const haystack = `${normalizeKey(baseTitle(entry))} ${entry.sectionId || ''}`;
  for (const [needle, image] of imageRules) {
    if (haystack.includes(needle)) return image;
  }
  return categoryDefaultImages.get(entry.sectionId) || 'situations.jpg';
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

const categories = await readJson(categoriesPath);
let translatedCategories = 0;
for (const category of categories) {
  if (!category.id?.startsWith('soundpad-')) continue;
  const russianName = categoryNames.get(category.id);
  if (!russianName) continue;
  if (category.name !== russianName) translatedCategories += 1;
  category.name = russianName;
}

const uploads = await readJson(uploadsPath);
let translatedSounds = 0;
let updatedImages = 0;
for (const item of uploads) {
  if (item.source !== 'soundpad-import') continue;
  const russianSectionName = categoryNames.get(item.sectionId);
  const russianTitle = translateTitle(item);
  const image = chooseImage(item);

  if (russianSectionName) item.sectionName = russianSectionName;
  if (item.title !== russianTitle) {
    item.title = russianTitle;
    translatedSounds += 1;
  }
  if (item.image !== image) {
    item.image = image;
    updatedImages += 1;
  }
}

await writeJson(categoriesPath, categories);
